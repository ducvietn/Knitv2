-- KNIT — lược đồ cơ sở dữ liệu Postgres (Supabase).
--
-- Đây là bản Postgres của lược đồ SQLite trong `server/src/lib/db.ts`.
-- Hai bản phải giữ cùng tên bảng/cột để lớp trừu hợp `server/src/lib/sql.ts`
-- chạy được với cả hai backend mà không cần rẽ nhánh trong mã nghiệp vụ.
--
-- Áp dụng:
--   - Qua Supabase CLI:  `supabase db push`
--   - Hoặc dán vào SQL Editor trên dashboard supabase.com.

-- ---------------------------------------------------------------------------
-- Người dùng
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id            TEXT PRIMARY KEY,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  display_name  TEXT NOT NULL,
  faculty_vi    TEXT NOT NULL,
  faculty_en    TEXT NOT NULL,
  cohort        TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('student','contributor','staff','admin')),
  verified      BOOLEAN NOT NULL DEFAULT FALSE,
  avatar_seed   TEXT NOT NULL,
  avatar_url    TEXT,
  avatar_tone   TEXT NOT NULL DEFAULT 'brand',
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- Câu hỏi
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS questions (
  id           TEXT PRIMARY KEY,
  title        TEXT NOT NULL,
  title_en     TEXT NOT NULL,
  body         TEXT NOT NULL,
  body_en      TEXT NOT NULL,
  topic        TEXT NOT NULL,
  author_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  also_need    INTEGER NOT NULL DEFAULT 0,
  views        INTEGER NOT NULL DEFAULT 0,
  anonymous    BOOLEAN NOT NULL DEFAULT FALSE,
  tags         JSONB NOT NULL DEFAULT '[]'::jsonb
);

-- ---------------------------------------------------------------------------
-- Câu trả lời (kèm biến thể ẩn danh và thông tin chuyển văn phòng)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS answers (
  id                   TEXT PRIMARY KEY,
  question_id          TEXT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  author_id            TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body                 TEXT NOT NULL,
  body_en              TEXT NOT NULL,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  accepted             BOOLEAN NOT NULL DEFAULT FALSE,
  helpful_count        INTEGER NOT NULL DEFAULT 0,
  -- biến thể "Trường hợp của mình khác"
  variant_context      TEXT,
  variant_context_en   TEXT,
  variant_anonymous    BOOLEAN,
  referral_office      TEXT,
  referral_office_en   TEXT,
  referral_note        TEXT,
  referral_note_en     TEXT
);

CREATE TABLE IF NOT EXISTS answer_sources (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  answer_id  TEXT NOT NULL REFERENCES answers(id) ON DELETE CASCADE,
  title      TEXT NOT NULL,
  url        TEXT NOT NULL,
  publisher  TEXT NOT NULL
);

-- ---------------------------------------------------------------------------
-- Tương tác
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS helpful_votes (
  answer_id TEXT NOT NULL REFERENCES answers(id) ON DELETE CASCADE,
  user_id   TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (answer_id, user_id)
);

CREATE TABLE IF NOT EXISTS also_need_votes (
  question_id TEXT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  user_id     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (question_id, user_id)
);

CREATE TABLE IF NOT EXISTS follows (
  user_id     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question_id TEXT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, question_id)
);

CREATE TABLE IF NOT EXISTS topic_follows (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  topic   TEXT NOT NULL,
  PRIMARY KEY (user_id, topic)
);

-- ---------------------------------------------------------------------------
-- Thông báo nội bộ
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS notifications (
  id          TEXT PRIMARY KEY,
  user_id     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind        TEXT NOT NULL,
  title       TEXT NOT NULL,
  title_en    TEXT NOT NULL,
  body        TEXT NOT NULL,
  body_en     TEXT NOT NULL,
  at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  read        BOOLEAN NOT NULL DEFAULT FALSE,
  question_id TEXT
);

-- ---------------------------------------------------------------------------
-- Báo cáo nội dung
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reports (
  id          TEXT PRIMARY KEY,
  user_id     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question_id TEXT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  answer_id   TEXT,
  reason      TEXT NOT NULL,
  detail      TEXT NOT NULL,
  status      TEXT NOT NULL DEFAULT 'open',
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- Chỉ mục
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_answers_question ON answers(question_id);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, read);
CREATE INDEX IF NOT EXISTS idx_reports_status ON reports(status);

-- Truy vấn danh sách câu hỏi luôn sắp theo thời điểm tạo.
CREATE INDEX IF NOT EXISTS idx_questions_created ON questions(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_questions_author ON questions(author_id);
CREATE INDEX IF NOT EXISTS idx_questions_topic ON questions(topic);
CREATE INDEX IF NOT EXISTS idx_answers_author ON answers(author_id);
CREATE INDEX IF NOT EXISTS idx_answer_sources_answer ON answer_sources(answer_id);
